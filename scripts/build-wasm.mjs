#!/usr/bin/env node
/**
 * Builds the WebAssembly form of the Rust crates whose rules the SDK shares with holzi, each the
 * one implementation of its rule (generated, not committed):
 *
 * - `haex-bundle` (crates/haex-bundle, bundle format `haextension-bundle/2`) into
 *   `src/bundle/wasm/`: glue `haex_bundle.js` / `.d.ts` (`--target web`, initialised synchronously
 *   in Node.js) and the module `haex_bundle_bg.wasm`, which `pnpm build` copies to `dist/` once
 *   for every Node.js entry.
 * - `haex-autofill` (the autofill rule) into `src/autofill/wasm/` and `haex-passgen` (the password
 *   generator) into `src/passgen/wasm/`: the glue and `module.ts`, the module as Base64, so the
 *   browser entries `@haex-space/vault-sdk/autofill` and `/passgen` carry it in their own code and
 *   work in a content script without fetching anything.
 *
 * Needs a Rust toolchain with the `wasm32-unknown-unknown` target and `wasm-bindgen` in the
 * version the crates pin (`wasm-bindgen = "=…"` in their Cargo.toml, the same in all of them).
 *
 * Usage: node scripts/build-wasm.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Each crate, where its glue goes, and whether the module is embedded as Base64. */
const CRATES = [
  { crate: "haex-bundle", out: join(ROOT, "src", "bundle", "wasm"), embed: false },
  { crate: "haex-autofill", out: join(ROOT, "src", "autofill", "wasm"), embed: true },
  { crate: "haex-passgen", out: join(ROOT, "src", "passgen", "wasm"), embed: true },
];

function tool(command, args, options = {}) {
  try {
    return execFileSync(command, args, options);
  } catch (error) {
    if (error.code === "ENOENT") {
      const hint =
        command === "wasm-bindgen"
          ? `cargo install wasm-bindgen-cli --version ${pinned("haex-bundle")}`
          : "install Rust (https://rustup.rs) and `rustup target add wasm32-unknown-unknown`";
      console.error(`✗ ${command} not found: ${hint}`);
      process.exit(1);
    }
    throw error;
  }
}

function pinned(crate) {
  const manifest = readFileSync(join(ROOT, "crates", crate, "Cargo.toml"), "utf8");
  return /wasm-bindgen = \{ version = "=([^"]+)"/.exec(manifest)?.[1];
}

const installed = tool("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim().split(" ").pop();

for (const { crate, out, embed } of CRATES) {
  const cwd = join(ROOT, "crates", crate);
  if (pinned(crate) !== installed) {
    throw new Error(`wasm-bindgen ${installed} is installed, ${crate} pins ${pinned(crate)}`);
  }
  tool("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "--features", "wasm", "--lib"], {
    cwd,
    stdio: "inherit",
  });
  // Cargo resolves CARGO_TARGET_DIR, `build.target-dir` and relative paths; ask it where it built.
  const { target_directory: targetDir } = JSON.parse(
    tool("cargo", ["metadata", "--format-version", "1", "--no-deps"], { cwd, encoding: "utf8" }),
  );
  const name = crate.replaceAll("-", "_");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const wasm = join(targetDir, "wasm32-unknown-unknown", "release", `${name}.wasm`);
  tool("wasm-bindgen", [wasm, "--target", "web", "--out-dir", out, "--out-name", name], {
    cwd,
    stdio: "inherit",
  });
  const module = join(out, `${name}_bg.wasm`);
  if (embed) {
    // The entry always hands the module over; without this default no bundler looks for the file.
    const glue = join(out, `${name}.js`);
    const fallback = `module_or_path = new URL('${name}_bg.wasm', import.meta.url);`;
    const source = readFileSync(glue, "utf8");
    if (!source.includes(fallback)) throw new Error(`${crate}: the glue changed, no default module path`);
    writeFileSync(glue, source.replace(fallback, `throw new Error("${crate}: no module given");`));
    const base64 = readFileSync(module).toString("base64");
    writeFileSync(
      join(out, "module.ts"),
      `// Generated by scripts/build-wasm.mjs: the WebAssembly module of ${crate}, as Base64.\n` +
        `export const MODULE_BASE64 = "${base64}";\n`,
    );
  }
  console.log(`✓ ${crate} wasm: ${statSync(module).size} bytes`);
}

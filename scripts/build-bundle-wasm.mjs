#!/usr/bin/env node
/**
 * Builds the WebAssembly form of the `haex-bundle` crate (crates/haex-bundle), the one
 * implementation of the bundle format `haextension-bundle/2`, into `src/bundle/wasm/`
 * (generated, not committed):
 *
 * - `haex_bundle.js` / `.d.ts`: the wasm-bindgen glue (`--target web`, initialised synchronously);
 * - `bytes.ts`: the module as base64, so tsup bundles it into `dist/` without copying files.
 *
 * Needs a Rust toolchain with the `wasm32-unknown-unknown` target and `wasm-bindgen` in the
 * version the crate pins (`wasm-bindgen = "=…"` in crates/haex-bundle/Cargo.toml).
 *
 * Usage: node scripts/build-bundle-wasm.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CRATE = join(ROOT, "crates", "haex-bundle");
const OUT_DIR = join(ROOT, "src", "bundle", "wasm");
const TARGET_DIR = process.env.CARGO_TARGET_DIR ?? join(CRATE, "target");

const pinned = /wasm-bindgen = \{ version = "=([^"]+)"/.exec(readFileSync(join(CRATE, "Cargo.toml"), "utf8"))?.[1];
const installed = execFileSync("wasm-bindgen", ["--version"], { encoding: "utf8" }).trim().split(" ").pop();
if (pinned !== installed) {
  throw new Error(`wasm-bindgen ${installed} is installed, the crate pins ${pinned}`);
}

const run = (command, args) => execFileSync(command, args, { cwd: CRATE, stdio: "inherit" });
run("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown", "--features", "wasm", "--lib"]);

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });
const wasm = join(TARGET_DIR, "wasm32-unknown-unknown", "release", "haex_bundle.wasm");
run("wasm-bindgen", [wasm, "--target", "web", "--out-dir", OUT_DIR, "--out-name", "haex_bundle"]);

const module = readFileSync(join(OUT_DIR, "haex_bundle_bg.wasm"));
writeFileSync(
  join(OUT_DIR, "bytes.ts"),
  `// Generated by scripts/build-bundle-wasm.mjs from crates/haex-bundle; do not edit.\n` +
    `export const WASM_BASE64 = "${module.toString("base64")}";\n`,
);
console.log(`✓ haex-bundle wasm: ${module.length} bytes`);
